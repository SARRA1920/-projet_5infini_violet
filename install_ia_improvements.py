    written = 0
    for relpath, b64 in FILES.items():
        dest = os.path.join(root, relpath)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        content = base64.b64decode(b64)
        with open(dest, "wb") as f:
            f.write(content)
        action = "cree" if not os.path.exists(dest + ".bak") else "ecrase"
        print("  [{:20s}] {} ({} octets)".format(action, relpath, len(content)))
        written += 1
    print("\n{} fichier(s) ecrit(s).".format(written))
    print("\nProchaines etapes :")
    print("  1. git add -A")
    print("  2. git commit -m \"feat(ia): feature importance, backtest, gauge de confiance\"")
    print("  3. relance le backend et le frontend pour verifier.")

